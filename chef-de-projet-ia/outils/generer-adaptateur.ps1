<#
.SYNOPSIS
  Regenerates modeles/AGENTS-snippet.md from the worker contract in the chef-de-projet-ia skill,
  so Codex/Gemini/local agents read the same text as Claude sessions.
  Usage: powershell -File outils\generer-adaptateur.ps1 [-Skill <path to SKILL.md>]
#>
param([string]$Skill = (Join-Path $env:USERPROFILE '.claude\skills\chef-de-projet-ia\SKILL.md'))
$ErrorActionPreference = 'Stop'
$utf8 = New-Object System.Text.UTF8Encoding($false)
$text = [IO.File]::ReadAllText($Skill, $utf8)
$m = [regex]::Match($text, '<!-- contrat:debut -->\r?\n(.*?)<!-- contrat:fin -->', 'Singleline')
if (-not $m.Success) { throw "contract markers not found in $Skill" }
$body = $m.Groups[1].Value.TrimEnd() -replace '^## ', '### '
$out = @"
<!-- Generated by outils/generer-adaptateur.ps1 from the chef-de-projet-ia skill. Do not edit here. -->
## Orchestration (for Codex, Gemini CLI and other agents)

Paste this section into a project's AGENTS.md (or GEMINI.md), replace ``<ORCH>`` with the orchestration folder
and ``<PREFIX>`` with the project's id prefix. Codex also reads skills from ``.agents/skills`` (repo) and
``~/.agents/skills`` (user): a copy of the chef-de-projet-ia skill there gives it the whole method.

$body
"@
$dest = Join-Path (Split-Path $PSScriptRoot -Parent) 'modeles\AGENTS-snippet.md'
[IO.File]::WriteAllText($dest, $out.Replace("`r`n", "`n") + "`n", $utf8)
Write-Output "written: modeles\AGENTS-snippet.md"
